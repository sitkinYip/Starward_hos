#!/usr/bin/env node
// Execute only the frozen, local E2E fixture factory with an inert Page adapter.
// This never opens a browser or sends network requests.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const Module = require('node:module');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const web = path.resolve(process.argv[2] || path.join(root, '../questions-web'));
const frozen = '4b7d1a0a00051ac630e459b0fd6c074f821d7455';
const actual = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: web, encoding: 'utf8' }).trim();
if (actual !== frozen) throw new Error('Web checkout changed; review and update the frozen baseline before exporting.');
const sourcePath = path.join(web, 'e2e/fixtures.ts');
const source = fs.readFileSync(sourcePath, 'utf8');
const committed = execFileSync('git', ['show', `${frozen}:e2e/fixtures.ts`], { cwd: web, encoding: 'utf8' });
if (source !== committed) throw new Error('Web fixture has uncommitted changes; use the frozen source.');
const sourceRequire = Module.createRequire(sourcePath);
const ts = sourceRequire('typescript');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const fixtureModule = new Module(sourcePath);
fixtureModule.filename = sourcePath;
fixtureModule.paths = Module._nodeModulePaths(web);
fixtureModule._compile(compiled, sourcePath);
(async () => {
  const { player, assignment } = await fixtureModule.exports.mockStarwardApi({ route: async () => {} }, { mustChange: true });
  assignment.serverTime = '2026-10-27T00:00:00.000Z';
  const fixtures = {
    WEB_PLAYER_JSON: player,
    WEB_ASSIGNMENT_JSON: assignment,
    WEB_ASSIGNMENTS_JSON: { items: [assignment] }
  };
  const outputDir = path.join(root, 'entry/src/test/fixtures');
  fs.mkdirSync(outputDir, { recursive: true });
  const lines = Object.entries(fixtures).map(([name, value]) => `export const ${name}: string = ${JSON.stringify(JSON.stringify(value))};`);
  fs.writeFileSync(path.join(outputDir, 'WebFixture.ets'), '// Generated by scripts/export-web-fixtures.cjs from the frozen Web E2E factory.\n' + lines.join('\n') + '\n');
  fs.writeFileSync(path.join(root, 'docs/fixtures-provenance.md'), `# 跨端响应夹具\n\n由 scripts/export-web-fixtures.cjs 直接执行冻结 Web 的 mockStarwardApi 导出，Page.route 为无操作适配器，不打开浏览器、不访问网络、不改源仓库。\n\n- Web commit: ${frozen}\n- Source: e2e/fixtures.ts\n- Source SHA-256: ${crypto.createHash('sha256').update(source).digest('hex')}\n- Options: mustChange=true；其他保持默认。\n- 唯一时间归一化：assignment.serverTime 固定 2026-10-27T00:00:00.000Z。\n- 产物：entry/src/test/fixtures/WebFixture.ets（完整玩家与未开始场次响应，包括 question=null）。\n\n原生只解码本切片需要的投影；未知字段保留在夹具但不宣称媒体/答题已迁移。该导出证明两端使用同一测试响应，不证明真实后端权限或网络。\n`);
  console.log('Exported frozen Web response fixtures without network access.');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
